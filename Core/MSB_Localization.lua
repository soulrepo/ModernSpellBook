-- Formatted lookup helper: MSB_L("UpcomingLabel", level)
-- Uses string.format-style placeholders in the locale string.
function MSB_L(key, ...)
    local str = Localization.current[key] or Localization.locales["enUS"][key] or key
    -- Lua 5.0: use the `arg` table for varargs (no `select` in RpLua 5.0).
    if (table.getn(arg) > 0) then
        return string.format(str, unpack(arg))
    end
    return str
end
